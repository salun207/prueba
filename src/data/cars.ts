import type { Silhouette } from '../render/CarBody';
import type { CarSpec } from '../sim/types';

export type Tier = 'D' | 'C' | 'B' | 'A' | 'S';

export interface BodyParams {
  /** Silueta lateral: define la forma real de la carrocería. */
  silhouette: Silhouette;
  length: number;
  width: number;
  height: number;
  /** 0..1 sobre el largo, dónde arranca y termina la cabina. */
  cabinStart: number;
  cabinEnd: number;
  cabinHeight: number;
  noseDrop: number;
  wedge: number;
  spoiler: 'none' | 'lip' | 'ducktail' | 'wing' | 'bigwing';
  wheelRadius: number;
  wheelWidth: number;
  fenderFlare: number;
}

export interface CarDefinition {
  id: string;
  displayName: string;
  tier: Tier;
  price: number;
  unlock: { type: 'start' | 'cash' | 'rep'; amount?: number };
  blurb: string;
  spec: CarSpec;
  body: BodyParams;
  defaultPaint: string;
  audio: { cylinders: number; turbo: boolean; character: 'inline4' | 'inline6' | 'v8' | 'rotary' | 'v12' | 'electric' };
}

